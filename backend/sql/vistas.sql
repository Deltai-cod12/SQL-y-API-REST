USE ComercialLaEstrella;
GO
/* 1. Facturacion por tienda y ubicacion. No duplicar ventas por detalles. */
CREATE OR ALTER VIEW dbo.Vista_Ventas_Ubicacion AS
WITH TotalesVenta AS (
    SELECT dv.VENTA_ID_VEN, SUM(CAST(dv.SUBTOTAL_DES_VEN AS DECIMAL(19,2))) AS TOTAL_VENTA
    FROM dbo.DESGLOSE_VENTA AS dv
    GROUP BY dv.VENTA_ID_VEN
)
SELECT
    t.ID_TI AS ID_TIENDA,
    t.NOMBRE_TI AS TIENDA,
    m.NOMBRE_MUN AS MUNICIPIO,
    d.NOMBRE_DEP AS DEPARTAMENTO,
    p.NOMBRE_PA AS PAIS,
    COUNT_BIG(*) AS CANTIDAD_VENTAS,
    CAST(SUM(COALESCE(tv.TOTAL_VENTA, 0)) AS DECIMAL(19,2)) AS TOTAL_FACTURADO
FROM dbo.VENTA AS v
INNER JOIN dbo.TIENDA AS t ON t.ID_TI = v.TIENDA_ID_TI
INNER JOIN dbo.MUNICIPIO AS m ON m.ID_MUN = t.MUNICIPIO_ID_MUN
INNER JOIN dbo.DEPARTAMENTO AS d ON d.ID_DEP = m.DEPARTAMENTO_ID_DEP
INNER JOIN dbo.PAIS AS p ON p.ID_PA = d.PAIS_ID_PA
LEFT JOIN TotalesVenta AS tv ON tv.VENTA_ID_VEN = v.ID_VEN
WHERE v.ESTADO_VENTA_ID_ES_VEN <> 3
GROUP BY t.ID_TI, t.NOMBRE_TI, m.NOMBRE_MUN, d.NOMBRE_DEP, p.NOMBRE_PA;
GO
/* 2. Unidades e ingresos por producto, excluyendo ventas anuladas. */
CREATE OR ALTER VIEW dbo.Vista_Top_Productos AS
SELECT
    pro.ID_PRO AS CODIGO_PRODUCTO,
    pro.NOMBRE_PRO AS PRODUCTO,
    cat.NOMBRE_CAT AS CATEGORIA,
    mar.NOMBRE_MAR AS MARCA,
    SUM(CAST(dv.CANTIDAD_DES_VEN AS BIGINT)) AS UNIDADES_VENDIDAS,
    CAST(SUM(CAST(dv.SUBTOTAL_DES_VEN AS DECIMAL(19,2))) AS DECIMAL(19,2)) AS MONTO_TOTAL_GENERADO
FROM dbo.DESGLOSE_VENTA AS dv
INNER JOIN dbo.VENTA AS v ON v.ID_VEN = dv.VENTA_ID_VEN
INNER JOIN dbo.PRODUCTO AS pro ON pro.ID_PRO = dv.PRODUCTO_ID_PRO
INNER JOIN dbo.CATEGORIA AS cat ON cat.ID_CAT = pro.CATEGORIA_ID_CAT
INNER JOIN dbo.MARCA AS mar ON mar.ID_MAR = pro.MARCA_ID_MAR
WHERE v.ESTADO_VENTA_ID_ES_VEN <> 3
GROUP BY pro.ID_PRO, pro.NOMBRE_PRO, cat.NOMBRE_CAT, mar.NOMBRE_MAR;
GO
/* 3. Saldos pendientes de ventas REGISTRADAS, evitando multiplicar pagos x detalles. */
CREATE OR ALTER VIEW dbo.Vista_Saldos_Pendientes AS
WITH Totales AS (
    SELECT dv.VENTA_ID_VEN, SUM(CAST(dv.SUBTOTAL_DES_VEN AS DECIMAL(19,2))) AS TOTAL_VENTA
    FROM dbo.DESGLOSE_VENTA AS dv
    GROUP BY dv.VENTA_ID_VEN
), Abonos AS (
    SELECT pa.VENTA_ID_VEN, SUM(CAST(pa.MONTO_PAG AS DECIMAL(19,2))) AS TOTAL_PAGADO
    FROM dbo.PAGO AS pa
    GROUP BY pa.VENTA_ID_VEN
)
SELECT
    v.ID_VEN AS ID_VENTA,
    v.FECHA_VEN AS FECHA_VENTA,
    v.TIENDA_ID_TI AS ID_TIENDA,
    v.CLIENTE_ID_CLI AS ID_CLIENTE,
    CAST(COALESCE(t.TOTAL_VENTA, 0) AS DECIMAL(19,2)) AS TOTAL_VENTA,
    CAST(COALESCE(a.TOTAL_PAGADO, 0) AS DECIMAL(19,2)) AS TOTAL_PAGADO,
    CAST(COALESCE(t.TOTAL_VENTA, 0) - COALESCE(a.TOTAL_PAGADO, 0) AS DECIMAL(19,2)) AS SALDO_PENDIENTE
FROM dbo.VENTA AS v
LEFT JOIN Totales AS t ON t.VENTA_ID_VEN = v.ID_VEN
LEFT JOIN Abonos AS a ON a.VENTA_ID_VEN = v.ID_VEN
WHERE v.ESTADO_VENTA_ID_ES_VEN = 1
  AND COALESCE(t.TOTAL_VENTA, 0) > COALESCE(a.TOTAL_PAGADO, 0);
GO
PRINT 'Vistas creadas o actualizadas correctamente';
SELECT name FROM sys.views
WHERE name IN ('Vista_Ventas_Ubicacion','Vista_Top_Productos','Vista_Saldos_Pendientes');
GO
